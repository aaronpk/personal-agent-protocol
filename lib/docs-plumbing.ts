import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import { ALL_DOCS_PAGES, docsHref, LATEST, VERSIONED_SLUGS, VERSIONS } from "../content/docs";

// The files that follow from the list of docs pages and versions: each page's .md route, and the
// docs redirects and headers in vercel.json. `pnpm docs:sync` writes them, and the build fails when
// they're out of date.

const ROOT = process.cwd();

export type PlumbingFile = { path: string; content: string };

// Next can't serve a dynamic route ending in .md, so each page has its own .md route file.
function mdRoute(href: string): PlumbingFile {
    const up = "../".repeat(href.split("/").length);
    return {
        path: `app${href}.md/route.ts`,
        content: `// Generated by \`pnpm docs:sync\` from the docs pages in content/docs.ts. Don't edit.
import { markdownResponse } from "${up}lib/docs-content";

export const dynamic = "force-static";

export function GET() {
    return markdownResponse("${href}");
}
`,
    };
}

type Redirect = { source: string; destination: string; permanent: boolean };
type Header = { source: string; headers: { key: string; value: string }[] };
type VercelConfig = { redirects: Redirect[]; headers: Header[] };

// The docs redirects: a URL without a version goes to the latest version that has the page, and a
// version's URL alone goes to its first page. Not permanent, since the latest version changes.
function docsRedirects(): Redirect[] {
    const pages = VERSIONED_SLUGS.flatMap((slug) => {
        const href = docsHref(slug);
        return href
            ? [
                  { source: `/docs/${slug}`, destination: href, permanent: false },
                  { source: `/docs/${slug}.md`, destination: `${href}.md`, permanent: false },
              ]
            : [];
    });
    return [
        {
            source: "/docs/:version(\\d+\\.\\d+)",
            destination: `/docs/:version/${LATEST.tabs[0].pages[0].slug}`,
            permanent: false,
        },
        ...pages,
    ];
}

// Only the latest version is indexed. Pages also say so in a robots meta tag, but .md files can't.
function docsHeaders(): Header[] {
    return VERSIONS.slice(1).map((v) => ({
        source: `/docs/${v.id}/(.*)`,
        headers: [{ key: "X-Robots-Tag", value: "noindex" }],
    }));
}

function isDocsRedirect(r: Redirect): boolean {
    const path = r.source.replace(/\.md$/, "");
    return (
        /^\/docs\/(\d|:version)/.test(r.source) ||
        VERSIONED_SLUGS.some((s) => path === `/docs/${s}`)
    );
}

function isDocsHeader(h: Header): boolean {
    return /^\/docs\/\d/.test(h.source);
}

// Replaces the entries `isOurs` matches with `ours`, where the first of them was, or at `fallback`.
function replace<T>(list: T[], isOurs: (item: T) => boolean, ours: T[], fallback: number): T[] {
    const at = list.findIndex(isOurs);
    const rest = list.filter((item) => !isOurs(item));
    const index = at < 0 ? fallback : list.slice(0, at).filter((item) => !isOurs(item)).length;
    return [...rest.slice(0, index), ...ours, ...rest.slice(index)];
}

function vercelJson(): PlumbingFile {
    const path = "vercel.json";
    const config = JSON.parse(readFileSync(join(ROOT, path), "utf8")) as VercelConfig;
    const docsRoot = config.redirects.findIndex((r) => r.source === "/docs");
    config.redirects = replace(config.redirects, isDocsRedirect, docsRedirects(), docsRoot + 1);
    config.headers = replace(config.headers, isDocsHeader, docsHeaders(), 0);
    return { path, content: JSON.stringify(config, null, 4) + "\n" };
}

// Every .md route file now in app/docs.
function existingMdRoutes(dir = join(ROOT, "app/docs")): string[] {
    return readdirSync(dir).flatMap((name) => {
        const path = join(dir, name);
        if (!statSync(path).isDirectory()) {
            return [];
        }
        const route = join(path, "route.ts");
        return name.endsWith(".md") && existsSync(route)
            ? [relative(ROOT, route)]
            : existingMdRoutes(path);
    });
}

export function plumbingFiles(): PlumbingFile[] {
    return [...ALL_DOCS_PAGES.map((page) => mdRoute(page.href)), vercelJson()];
}

// .md route files for pages that no longer exist.
export function extraPlumbing(): string[] {
    const expected = new Set(plumbingFiles().map((file) => file.path));
    return existingMdRoutes().filter((path) => !expected.has(path));
}

// Files that are missing, changed, or no longer needed.
export function stalePlumbing(): string[] {
    const stale = plumbingFiles()
        .filter((file) => {
            const path = join(ROOT, file.path);
            return !existsSync(path) || readFileSync(path, "utf8") !== file.content;
        })
        .map((file) => file.path);
    return [...stale, ...extraPlumbing()];
}
